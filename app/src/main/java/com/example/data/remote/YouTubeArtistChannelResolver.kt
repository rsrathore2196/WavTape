package com.example.data.remote

import android.net.Uri
import android.util.LruCache
import com.example.data.repository.CatalogArtist
import com.example.data.repository.CatalogArtistProfile
import com.example.data.repository.CatalogNames
import com.example.performance.AppDispatchers
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.withContext
import org.json.JSONArray
import org.json.JSONObject
import java.util.Locale
import java.util.concurrent.TimeUnit
import kotlin.math.log10

/**
 * Resolves an artist's real YouTube channel (Official Artist Channel / verified channel),
 * explicitly rejecting auto-generated YouTube Music "- Topic" channels and unrelated fan pages.
 */
object YouTubeArtistChannelResolver {
    private val YOUTUBE_CHANNEL_ID = Regex("^UC[A-Za-z0-9_-]{10,}$")
    private val TOPIC_SUFFIX = Regex("(?i)\\s*[-–—]\\s*topic\\s*$")
    private val OFFICIAL_SUFFIX = Regex("(?i)(?:\\s*[-–—|]\\s*|\\s+)(?:official(?:\\s+channel|\\s+music|\\s+artist)?|music|vevo|channel|tv|records|live|audio|songs)$")
    private val COMPACT_VEVO_SUFFIX = Regex("(?i)(?:vevo|official|music)$")
    private val UNOFFICIAL_WORDS = setOf(
        "fan", "fans", "fanclub", "fc", "club", "status", "lyrics", "lyric",
        "lofi", "slowed", "reverb", "mashup", "mashups", "remix", "remixes",
        "cover", "covers", "tribute", "reaction", "reactions", "karaoke",
        "shorts", "edits", "edit", "updates", "army", "lover", "lovers",
        "clips", "vlog", "vlogs", "podcast", "memes", "ringtone", "ringtones"
    )
    private val SUBSCRIBER_NUMBER = Regex("(?i)([0-9]+(?:\\.[0-9]+)?)\\s*([KMB])?")
    private const val CHANNEL_SEARCH_PARAMS = "EgIQAg=="
    private val cacheTtlMs = TimeUnit.HOURS.toMillis(24)
    private val resolvedCache = LruCache<String, Pair<Long, String>>(128)

    internal fun isValidChannelId(id: String): Boolean = YOUTUBE_CHANNEL_ID.matches(id.trim())

    internal fun isTopicTitle(title: String): Boolean = TOPIC_SUFFIX.containsMatchIn(title.trim())

    internal fun isAutoGeneratedDescription(description: String): Boolean =
        description.contains("Auto-generated by YouTube", ignoreCase = true)

    internal fun clearCache() {
        resolvedCache.evictAll()
    }

    internal fun cachedUrl(artist: CatalogArtist, profile: CatalogArtistProfile? = null): String? {
        val direct = profile?.youtubeChannelUrl?.trim().orEmpty()
        if (isDirectChannelUrl(direct)) return direct
        val key = cacheKey(artist, profile) ?: return null
        val entry = resolvedCache.get(key) ?: return null
        return if (entry.first > System.currentTimeMillis()) entry.second else null
    }

    /**
     * Safe synchronous fallback when offline or before live resolution finishes.
     * Never blindly treats a raw YouTube Music browseId (often a "- Topic" channel) as the artist's
     * real YouTube channel unless the artist header explicitly provided a distinct subscribe channelId.
     */
    internal fun fallbackYouTubeUrl(artist: CatalogArtist, profile: CatalogArtistProfile? = null): String {
        val verifiedUrl = profile?.youtubeChannelUrl?.trim().orEmpty()
        if (isDirectChannelUrl(verifiedUrl)) return verifiedUrl
        val subscribeId = profile?.youtubeChannelId?.trim().orEmpty()
        val browseId = artist.id.trim()
        if (isValidChannelId(subscribeId) && subscribeId != browseId) {
            return "https://www.youtube.com/channel/$subscribeId"
        }
        val query = artist.name.trim()
        return if (query.isNotBlank()) {
            "https://www.youtube.com/results?search_query=${Uri.encode(query)}"
        } else {
            "https://www.youtube.com/"
        }
    }

    suspend fun resolveArtistYouTubeUrl(
        artist: CatalogArtist,
        profile: CatalogArtistProfile? = null,
        browseWeb: suspend (String) -> String = { id ->
            YouTubeMusicApiService.postYouTubeWeb("browse", JSONObject().put("browseId", id))
        },
        searchWeb: suspend (String) -> String = { query ->
            YouTubeMusicApiService.postYouTubeWeb(
                "search",
                JSONObject().put("query", query).put("params", CHANNEL_SEARCH_PARAMS)
            )
        }
    ): String {
        val name = artist.name.trim()
        val key = cacheKey(artist, profile)
        cachedUrl(artist, profile)?.let { return it }

        val candidates = buildList {
            val subId = profile?.youtubeChannelId?.trim().orEmpty()
            val browseId = artist.id.trim()
            if (isValidChannelId(subId)) add(subId)
            if (isValidChannelId(browseId) && browseId != subId) add(browseId)
        }

        for (candidateId in candidates) {
            val verified = try {
                val body = browseWeb(candidateId)
                withContext(AppDispatchers.CpuBounded) {
                    parseVerifiedWebChannel(JSONObject(body), name, candidateId)
                }
            } catch (cancelled: CancellationException) {
                throw cancelled
            } catch (_: Exception) {
                null
            }
            if (verified != null) {
                cacheResolved(key, verified)
                return verified
            }
        }

        if (name.isNotBlank()) {
            val searched = try {
                val body = searchWeb(name)
                withContext(AppDispatchers.CpuBounded) {
                    pickBestChannelFromSearch(JSONObject(body), name)
                }
            } catch (cancelled: CancellationException) {
                throw cancelled
            } catch (_: Exception) {
                null
            }
            if (searched != null) {
                cacheResolved(key, searched)
                return searched
            }
        }

        return fallbackYouTubeUrl(artist, profile)
    }

    internal fun parseVerifiedWebChannel(
        root: JSONObject,
        artistName: String,
        requestedId: String
    ): String? {
        val header = root.optJSONObject("header")
        if (header?.has("topicChannelDetailsRenderer") == true ||
            header?.has("carouselHeaderRenderer") == true
        ) {
            return null
        }

        val metadata = root.optJSONObject("metadata")?.optJSONObject("channelMetadataRenderer")
        val microformat = root.optJSONObject("microformat")?.optJSONObject("microformatDataRenderer")
        val headerTitle = extractWebHeaderTitle(header)
        val title = metadata?.optString("title").orEmpty().trim()
            .ifBlank { microformat?.optString("title").orEmpty().trim() }
            .ifBlank { headerTitle }
        val description = metadata?.optString("description").orEmpty().trim()
            .ifBlank { microformat?.optString("description").orEmpty().trim() }

        if (title.isBlank() || isTopicTitle(title) || isAutoGeneratedDescription(description)) {
            return null
        }

        val externalId = metadata?.optString("externalId").orEmpty().trim()
            .takeIf(::isValidChannelId)
            ?: extractChannelIdFromUrl(metadata?.optString("channelUrl").orEmpty())
            ?: extractChannelIdFromUrl(microformat?.optString("urlCanonical").orEmpty())
            ?: requestedId.trim().takeIf(::isValidChannelId)
            ?: return null

        val isOfficialArtist = hasOfficialArtistBadge(header)
        if (artistName.isNotBlank()) {
            if (containsUnofficialNoise(title, artistName)) return null
            val matchKind = evaluateNameMatch(artistName, title, metadata?.optString("vanityChannelUrl").orEmpty())
            if (matchKind == NameMatch.NONE && !isOfficialArtist) return null
        }

        return "https://www.youtube.com/channel/$externalId"
    }

    internal fun pickBestChannelFromSearch(root: JSONObject, artistName: String): String? {
        if (artistName.isBlank()) return null
        val candidates = mutableListOf<ChannelCandidate>()
        var order = 0
        walkObjects(root) { node ->
            val renderer = node.optJSONObject("channelRenderer") ?: return@walkObjects true
            val channelId = renderer.optString("channelId").trim()
            val title = extractText(renderer.optJSONObject("title"))
            val description = extractText(renderer.optJSONObject("descriptionSnippet"))
            if (!isValidChannelId(channelId) || title.isBlank() ||
                isTopicTitle(title) || isAutoGeneratedDescription(description) ||
                containsUnofficialNoise(title, artistName)
            ) {
                return@walkObjects false
            }

            val subText = extractText(renderer.optJSONObject("subscriberCountText"))
            val vidText = extractText(renderer.optJSONObject("videoCountText"))
            val canonicalBaseUrl = renderer.optJSONObject("navigationEndpoint")
                ?.optJSONObject("browseEndpoint")
                ?.optString("canonicalBaseUrl")
                .orEmpty()
            val handleCandidate = canonicalBaseUrl.ifBlank { subText }
            val badges = parseBadges(renderer.optJSONArray("ownerBadges"))
            val matchKind = evaluateNameMatch(artistName, title, handleCandidate)
            val normalizedArtist = CatalogNames.normalize(artistName)
            val normalizedTitle = CatalogNames.normalize(title)
            val artistMentioned = normalizedArtist.isNotBlank() &&
                (" $normalizedTitle ".contains(" $normalizedArtist ") ||
                    normalizedTitle.replace(" ", "").contains(normalizedArtist.replace(" ", "")))

            val eligible = when {
                badges.isOfficialArtist && (matchKind != NameMatch.NONE || artistMentioned) -> true
                badges.isVerified && matchKind != NameMatch.NONE -> true
                matchKind == NameMatch.EXACT || matchKind == NameMatch.OFFICIAL_VARIANT -> true
                else -> false
            }
            if (eligible) {
                val subscribers = maxOf(parseSubscriberCount(subText), parseSubscriberCount(vidText))
                val handleExact = handleMatchesArtist(artistName, canonicalBaseUrl) ||
                    handleMatchesArtist(artistName, subText)
                var score = 0.0
                if (badges.isOfficialArtist) score += 1000.0
                if (badges.isVerified) score += 400.0
                score += when (matchKind) {
                    NameMatch.EXACT -> 300.0
                    NameMatch.OFFICIAL_VARIANT -> 200.0
                    NameMatch.HANDLE_ONLY -> 120.0
                    NameMatch.NONE -> 0.0
                }
                if (handleExact) score += 50.0
                if (subscribers > 0.0) score += log10(subscribers + 1.0) * 12.0
                score -= order * 2.0
                candidates += ChannelCandidate(channelId, score)
            }
            order++
            false
        }
        val best = candidates.maxByOrNull { it.score } ?: return null
        return "https://www.youtube.com/channel/${best.channelId}"
    }

    private enum class NameMatch { NONE, HANDLE_ONLY, OFFICIAL_VARIANT, EXACT }
    private data class BadgeInfo(val isOfficialArtist: Boolean, val isVerified: Boolean)
    private data class ChannelCandidate(val channelId: String, val score: Double)

    private fun evaluateNameMatch(artistName: String, channelTitle: String, urlOrHandle: String): NameMatch {
        if (CatalogNames.same(artistName, channelTitle)) return NameMatch.EXACT
        val strippedTitle = stripOfficialSuffix(channelTitle)
        if (strippedTitle.isNotBlank() && CatalogNames.same(artistName, strippedTitle)) {
            return NameMatch.OFFICIAL_VARIANT
        }
        val compactArtist = CatalogNames.normalize(artistName).replace(" ", "")
        val compactTitle = CatalogNames.normalize(channelTitle).replace(" ", "")
        if (compactArtist.isNotBlank() && compactTitle.isNotBlank()) {
            if (compactArtist == compactTitle) return NameMatch.EXACT
            val compactStripped = COMPACT_VEVO_SUFFIX.replace(compactTitle, "")
            if (compactStripped.isNotBlank() && compactStripped == compactArtist) {
                return NameMatch.OFFICIAL_VARIANT
            }
        }
        if (handleMatchesArtist(artistName, urlOrHandle)) return NameMatch.HANDLE_ONLY
        return NameMatch.NONE
    }

    private fun stripOfficialSuffix(title: String): String {
        var current = title.trim()
        repeat(2) {
            val next = OFFICIAL_SUFFIX.replace(current, "").trim()
            if (next == current) return current
            current = next
        }
        return current
    }

    private fun handleMatchesArtist(artistName: String, urlOrHandle: String): Boolean {
        val raw = urlOrHandle.trim()
        val atIndex = raw.indexOf("/@")
        val handle = when {
            atIndex >= 0 -> raw.substring(atIndex + 2).substringBefore('/').substringBefore('?')
            raw.startsWith("@") -> raw.substring(1).substringBefore('/').substringBefore('?')
            else -> ""
        }
        if (handle.isBlank()) return false
        val compactArtist = CatalogNames.normalize(artistName).replace(" ", "")
        val compactHandle = CatalogNames.normalize(handle).replace(" ", "")
        if (compactArtist.isBlank() || compactHandle.isBlank()) return false
        return compactHandle == compactArtist ||
            COMPACT_VEVO_SUFFIX.replace(compactHandle, "") == compactArtist
    }

    private fun containsUnofficialNoise(channelTitle: String, artistName: String): Boolean {
        val artistWords = CatalogNames.normalize(artistName).split(' ').filter(String::isNotBlank).toSet()
        val titleWords = CatalogNames.normalize(channelTitle).split(' ').filter(String::isNotBlank)
        return titleWords.any { word -> word in UNOFFICIAL_WORDS && word !in artistWords }
    }

    private fun parseBadges(array: JSONArray?): BadgeInfo {
        if (array == null) return BadgeInfo(false, false)
        var official = false
        var verified = false
        for (i in 0 until array.length()) {
            val badge = array.optJSONObject(i)?.optJSONObject("metadataBadgeRenderer") ?: continue
            val style = badge.optString("style")
            val icon = badge.optJSONObject("icon")?.optString("iconType").orEmpty()
            val tooltip = badge.optString("tooltip")
            if (style == "BADGE_STYLE_TYPE_VERIFIED_ARTIST" ||
                icon == "OFFICIAL_ARTIST_BADGE" ||
                icon == "MUSIC_FILLED" ||
                tooltip.contains("Official Artist", ignoreCase = true)
            ) {
                official = true
            } else if (style == "BADGE_STYLE_TYPE_VERIFIED" ||
                icon == "CHECK_CIRCLE_THICK" ||
                tooltip.equals("Verified", ignoreCase = true)
            ) {
                verified = true
            }
        }
        return BadgeInfo(official, verified)
    }

    private fun hasOfficialArtistBadge(header: JSONObject?): Boolean {
        if (header == null) return false
        var found = false
        walkObjects(header) { node ->
            if (found) return@walkObjects false
            val style = node.optString("style")
            val iconType = node.optString("iconType")
            val iconName = node.optString("iconName")
            val tooltip = node.optString("tooltip")
            val a11y = node.optString("accessibilityLabel")
            if (style == "BADGE_STYLE_TYPE_VERIFIED_ARTIST" ||
                iconType == "OFFICIAL_ARTIST_BADGE" ||
                iconName == "OFFICIAL_ARTIST_BADGE" ||
                iconName == "MUSIC_FILLED" ||
                tooltip.contains("Official Artist", ignoreCase = true) ||
                a11y.contains("Official Artist", ignoreCase = true)
            ) {
                found = true
                return@walkObjects false
            }
            true
        }
        return found
    }

    private fun extractWebHeaderTitle(header: JSONObject?): String {
        if (header == null) return ""
        val c4 = header.optJSONObject("c4TabbedHeaderRenderer")?.optString("title").orEmpty().trim()
        if (c4.isNotBlank()) return c4
        val pageTitle = header.optJSONObject("pageHeaderRenderer")?.optString("pageTitle").orEmpty().trim()
        if (pageTitle.isNotBlank()) return pageTitle
        return header.optJSONObject("pageHeaderRenderer")
            ?.optJSONObject("content")
            ?.optJSONObject("pageHeaderViewModel")
            ?.optJSONObject("title")
            ?.optJSONObject("dynamicTextViewModel")
            ?.optJSONObject("text")
            ?.optString("content")
            .orEmpty()
            .trim()
    }

    private fun extractChannelIdFromUrl(url: String): String? {
        val marker = "/channel/"
        val index = url.indexOf(marker)
        if (index < 0) return null
        val candidate = url.substring(index + marker.length).substringBefore('/').substringBefore('?').trim()
        return candidate.takeIf(::isValidChannelId)
    }

    private fun isDirectChannelUrl(url: String): Boolean {
        if (!url.startsWith("https://www.youtube.com/")) return false
        val path = url.removePrefix("https://www.youtube.com/")
        return path.startsWith("channel/UC") || path.startsWith("@")
    }

    private fun parseSubscriberCount(text: String): Double {
        if (!text.contains("subscriber", ignoreCase = true)) return 0.0
        val match = SUBSCRIBER_NUMBER.find(text) ?: return 0.0
        val base = match.groupValues[1].toDoubleOrNull() ?: return 0.0
        return when (match.groupValues[2].uppercase(Locale.ROOT)) {
            "B" -> base * 1_000_000_000.0
            "M" -> base * 1_000_000.0
            "K" -> base * 1_000.0
            else -> base
        }
    }

    private fun extractText(node: JSONObject?): String {
        if (node == null) return ""
        node.optString("simpleText").takeIf(String::isNotBlank)?.let { return it.trim() }
        node.optString("content").takeIf(String::isNotBlank)?.let { return it.trim() }
        val runs = node.optJSONArray("runs") ?: return ""
        val builder = StringBuilder()
        for (i in 0 until runs.length()) {
            builder.append(runs.optJSONObject(i)?.optString("text").orEmpty())
        }
        return builder.toString().trim()
    }

    private fun cacheKey(artist: CatalogArtist, profile: CatalogArtistProfile?): String? {
        val name = CatalogNames.normalize(artist.name)
        val id = profile?.youtubeChannelId?.trim().takeIf { !it.isNullOrBlank() } ?: artist.id.trim()
        if (name.isBlank() && id.isBlank()) return null
        return "$id|$name"
    }

    private fun cacheResolved(key: String?, url: String) {
        if (key != null && isDirectChannelUrl(url)) {
            resolvedCache.put(key, (System.currentTimeMillis() + cacheTtlMs) to url)
        }
    }

    private fun walkObjects(value: Any?, visit: (JSONObject) -> Boolean) {
        when (value) {
            is JSONObject -> {
                if (!visit(value)) return
                val keys = value.keys()
                while (keys.hasNext()) {
                    walkObjects(value.opt(keys.next()), visit)
                }
            }
            is JSONArray -> {
                for (i in 0 until value.length()) {
                    walkObjects(value.opt(i), visit)
                }
            }
        }
    }
}
